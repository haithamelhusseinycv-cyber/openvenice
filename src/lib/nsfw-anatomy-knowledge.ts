/**
 * Build a comprehensive NSFW prompt with anatomy, positioning, and professional techniques
 */
export function buildNSFWPrompt(options: {
  position?: string
  anatomy?: string[]
  lighting?: string
  cameraAngle?: string
  composition?: string
  focusType?: string
  colorTone?: string
  additionalDetails?: string[]
}): string {
  const parts: string[] = []

  // Base quality
  parts.push('highly detailed, professional photography, sharp focus, 8k uhd')
  parts.push('realistic skin texture, natural body proportions, accurate human anatomy')

  // Position
  if (options.position) {
    const position = SEXUAL_POSITIONS.find((p) => p.id === options.position)
    if (position) {
      parts.push(position.promptKeywords.join(', '))
    }
  }

  // Anatomy focus
  if (options.anatomy?.length) {
    parts.push(options.anatomy.join(', '))
  }

  // Lighting
  if (options.lighting) {
    const lighting = PROFESSIONAL_TECHNIQUES.find((t) => t.category === 'Lighting')
      ?.techniques.find((t) => t.name.toLowerCase().includes(options.lighting!.toLowerCase()))
    if (lighting) {
      parts.push(lighting.promptKeywords.join(', '))
    }
  }

  // Camera angle
  if (options.cameraAngle) {
    const angle = PROFESSIONAL_TECHNIQUES.find((t) => t.category === 'Camera Angles')
      ?.techniques.find((t) => t.name.toLowerCase().includes(options.cameraAngle!.toLowerCase()))
    if (angle) {
      parts.push(angle.promptKeywords.join(', '))
    }
  }

  // Composition
  if (options.composition) {
    const comp = PROFESSIONAL_TECHNIQUES.find((t) => t.category === 'Composition')
      ?.techniques.find((t) => t.name.toLowerCase().includes(options.composition!.toLowerCase()))
    if (comp) {
      parts.push(comp.promptKeywords.join(', '))
    }
  }

  // Focus
  if (options.focusType) {
    const focus = PROFESSIONAL_TECHNIQUES.find((t) => t.category === 'Focus and Depth')
      ?.techniques.find((t) => t.name.toLowerCase().includes(options.focusType!.toLowerCase()))
    if (focus) {
      parts.push(focus.promptKeywords.join(', '))
    }
  }

  // Color tone
  if (options.colorTone) {
    const tone = PROFESSIONAL_TECHNIQUES.find((t) => t.category === 'Color and Tone')
      ?.techniques.find((t) => t.name.toLowerCase().includes(options.colorTone!.toLowerCase()))
    if (tone) {
      parts.push(tone.promptKeywords.join(', '))
    }
  }

  // Additional details
  if (options.additionalDetails?.length) {
    parts.push(options.additionalDetails.join(', '))
  }

  return parts.join(', ')
}

